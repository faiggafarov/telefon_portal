-- ========================================================
-- Database Schema for KYLTM Employee Portal
-- PostgreSQL Dialect
-- ========================================================

-- 1. Departments Domain Table (Şöbələr)
CREATE TABLE IF NOT EXISTS departments (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL UNIQUE,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT departments_pkey PRIMARY KEY (id)
);

-- 2. Sectors Domain Table (Sektorlar — Şöbəyə bağlıdır)
CREATE TABLE IF NOT EXISTS sectors (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    dept_id bigint NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT sectors_pkey PRIMARY KEY (id),
    CONSTRAINT sectors_name_dept_unique UNIQUE (name, dept_id)
);

-- 3. Positions Domain Table (Vəzifələr)
CREATE TABLE IF NOT EXISTS positions (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL UNIQUE,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT positions_pkey PRIMARY KEY (id)
);

-- 4. Employees Table (Əməkdaşlar)
CREATE TABLE IF NOT EXISTS employees (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    name text NOT NULL,
    position_id bigint NOT NULL REFERENCES positions(id) ON DELETE CASCADE,
    dept_id bigint NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    sector_id bigint REFERENCES sectors(id) ON DELETE SET NULL,
    email text,
    intphone text,
    mobile text,
    room text,
    car_plate text,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    CONSTRAINT employees_pkey PRIMARY KEY (id)
);

-- 5. Employee Edit Requests Table (Redaktə və Yeni Əməkdaş Sorğuları)
CREATE TABLE IF NOT EXISTS employee_edit_requests (
    id integer NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    employee_id integer,
    employee_name text,
    old_data jsonb,
    new_data jsonb,
    status text DEFAULT 'pending'::text,
    requested_by text,
    request_type text DEFAULT 'edit'::text,
    requested_at timestamp with time zone DEFAULT now(),
    resolved_at timestamp with time zone,
    CONSTRAINT employee_edit_requests_pkey PRIMARY KEY (id)
);

-- 6. Portal Users Table (Admin və İdarəçilər)
CREATE TABLE IF NOT EXISTS portal_users (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    username text NOT NULL UNIQUE,
    email text NOT NULL,
    role text NOT NULL DEFAULT 'user'::text,
    password text NOT NULL,
    is_active boolean NOT NULL DEFAULT true,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    CONSTRAINT portal_users_pkey PRIMARY KEY (id)
);

-- Indexes for performance
CREATE INDEX IF NOT EXISTS idx_sectors_dept_id ON sectors(dept_id);
CREATE INDEX IF NOT EXISTS idx_employees_dept_id ON employees(dept_id);
CREATE INDEX IF NOT EXISTS idx_employees_sector_id ON employees(sector_id);
CREATE INDEX IF NOT EXISTS idx_employees_position_id ON employees(position_id);
CREATE INDEX IF NOT EXISTS idx_employee_edit_requests_status ON employee_edit_requests(status);

-- 7. Meetings Table (İclas Otağı / Rezervasiyalar)
CREATE TABLE IF NOT EXISTS meetings (
    id bigint NOT NULL GENERATED BY DEFAULT AS IDENTITY,
    title text NOT NULL,
    organizer text NOT NULL,
    dept_id bigint NOT NULL REFERENCES departments(id) ON DELETE CASCADE,
    meeting_date date NOT NULL,
    start_time time NOT NULL,
    end_time time NOT NULL,
    description text,
    participants jsonb DEFAULT '[]'::jsonb,
    created_at timestamp with time zone NOT NULL DEFAULT now(),
    updated_at timestamp with time zone DEFAULT now(),
    CONSTRAINT meetings_pkey PRIMARY KEY (id)
);
CREATE INDEX IF NOT EXISTS idx_meetings_date ON meetings(meeting_date);
